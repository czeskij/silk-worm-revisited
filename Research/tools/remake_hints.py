"""Write remake/js/hints.js: what each enemy wave routine looks like.

usage: remake_hints.py CHIPMEM.bin OUT.js

Only analysis results go in the file (sprite numbers, group sizes, start
positions per routine address); the remake reads the wave scripts and all
graphics from the player's own ADF at runtime.
"""
import json
import re
import struct
import sys

import capstone

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from waves import NAMES, scripts, walk  # noqa: E402

md = capstone.Cs(capstone.CS_ARCH_M68K, capstone.CS_MODE_M68K_000)


def start_position(mem, addr):
    """First `move.w #x,(a5)` / `move.w #y,$4(a5)` along the routine's path."""
    x = y = None
    pc, seen = addr, set()
    for _ in range(80):
        if pc in seen:
            break
        seen.add(pc)
        ins = next(md.disasm(mem[pc:pc + 10], pc), None)
        if ins is None:
            break
        m = re.fullmatch(r"#\$([0-9a-f]+), \(a5\)", ins.op_str)
        if ins.mnemonic == "move.w" and m and x is None:
            x = int(m.group(1), 16)
        m = re.fullmatch(r"#\$([0-9a-f]+), \$4\(a5\)", ins.op_str)
        if ins.mnemonic == "move.w" and m and y is None:
            y = int(m.group(1), 16)
        if ins.mnemonic in ("bra.b", "bra.w"):
            pc = int(re.search(r"\$([0-9a-f]+)$", ins.op_str).group(1), 16)
            continue
        if ins.mnemonic in ("rts", "jmp"):
            break
        pc += ins.size
    return x, y


def main():
    mem = open(sys.argv[1], "rb").read()
    hints = {}
    for lv, ev in scripts(mem).items():
        for _, addr, _ in ev:
            count, frames = walk(mem, addr, lv)
            x, y = start_position(mem, addr)
            h = hints.setdefault("%X" % addr, {"count": count or 1, "x": x, "y": y, "frames": {}})
            if frames:
                h["frames"][lv] = frames[0]
            if addr in NAMES:
                h["name"] = NAMES[addr]
    with open(sys.argv[2], "w") as f:
        f.write("// Generated by Research/tools/remake_hints.py: per wave routine (address),\n")
        f.write("// group size, start position if fixed, and main animation per level.\n")
        f.write("window.HINTS = ")
        json.dump(hints, f, separators=(",", ":"))
        f.write(";\n")
    print(len(hints), "routines")


if __name__ == "__main__":
    main()
